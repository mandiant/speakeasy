#!/usr/bin/env python3
"""
Generate the enum classes of speakeasy/winenv/defs/enums.py from win32json.

``scripts/win32_enums.json`` lists the classes. Each win32json enum gets the members that the
signature database has for it, from ``get_enum_values`` of ``gen_win32_signatures.py``, so the
handlers and the signature database decode a value to the same names. A constant set gets the
values of the win32json constants that it lists.

Usage::

    python scripts/gen_win32_enums.py [--win32json DIR] [--spec FILE] [--overrides FILE] [--output FILE]
"""

from __future__ import annotations

import argparse
import json
import os
import sys

from gen_win32_signatures import (
    DEFAULT_OVERRIDES,
    DEFAULT_WIN32JSON,
    REPO_ROOT,
    get_enum_values,
    load_overrides,
    load_win32json,
)

DEFAULT_SPEC = os.path.join(REPO_ROOT, "scripts", "win32_enums.json")
DEFAULT_OUTPUT = os.path.join(REPO_ROOT, "speakeasy", "winenv", "defs", "enums.py")

HEADER = '''\
# Generated by scripts/gen_win32_enums.py from win32json. Do not edit.
"""The Windows SDK enums and flag sets that handlers decode, with the values of win32json."""

from enum import IntEnum, IntFlag
'''


def render_value(value: int, flags: bool) -> str:
    if flags:
        return f"0x{value:08X}"
    return str(value) if value < 0x10000 else f"0x{value:X}"


def render_class(name: str, flags: bool, members: list[list], doc: str | None = None) -> str:
    """
    Render one class.

    Raises:
        SystemExit: a member name cannot be an enum member.
    """
    lines = [f"class {name}({'IntFlag' if flags else 'IntEnum'}):"]
    if doc:
        lines += [f'    """{doc}"""', ""]
    for member, value in members:
        if not member.isidentifier() or member.startswith("_"):
            raise SystemExit(f"{name}: member {member!r} is not a valid enum member name")
        lines.append(f"    {member} = {render_value(value, flags)}")
    return "\n".join(lines) + "\n"


def render_module(spec: dict, enums: dict[str, dict], constants: dict[str, int], overrides: dict) -> str:
    """
    Render the module with the classes of spec, sorted by name.

    Raises:
        SystemExit: spec names an enum or a constant that win32json does not have.
    """
    classes = {}
    for name in spec["enums"]:
        td = enums.get(name)
        if td is None:
            raise SystemExit(f"enum {name!r} not found in win32json")
        classes[name] = render_class(name, bool(td.get("Flags")), get_enum_values(td, constants, overrides))
    for name, cs in spec["constant_sets"].items():
        if name in classes or name in enums:
            raise SystemExit(f"constant set {name!r} has the name of a win32json enum")
        missing = [c for c in cs["names"] if c not in constants]
        if missing:
            raise SystemExit(f"constant set {name}: constants {missing} not found in win32json")
        members = [[c, constants[c] & 0xFFFFFFFF] for c in cs["names"]]
        classes[name] = render_class(name, cs["flags"], members, cs.get("doc"))
    return HEADER + "".join(f"\n\n{classes[name]}" for name in sorted(classes))


def get_enum_types(namespaces: dict[str, dict[str, dict]]) -> dict[str, dict]:
    return {name: td for ns in namespaces.values() for name, td in ns.items() if td["Kind"] == "Enum"}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.strip().split("\n\n")[0])
    ap.add_argument("--win32json", default=DEFAULT_WIN32JSON, help="path to the win32json checkout")
    ap.add_argument("--spec", default=DEFAULT_SPEC, help="path to win32_enums.json")
    ap.add_argument("--overrides", default=DEFAULT_OVERRIDES, help="path to win32_overrides.json")
    ap.add_argument("--output", default=DEFAULT_OUTPUT, help="output .py path")
    args = ap.parse_args(argv)

    namespaces, _, constants = load_win32json(args.win32json)
    with open(args.spec, encoding="utf-8") as f:
        spec = json.load(f)
    source = render_module(spec, get_enum_types(namespaces), constants, load_overrides(args.overrides))
    with open(args.output, "w", encoding="utf-8") as f:
        f.write(source)
    print(f"wrote {args.output}: {len(spec['enums']) + len(spec['constant_sets'])} classes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
